async function pipelineCookie(request,env,unseal){
 const cookies=(request.headers.get('Cookie')||'').split(';').map(s=>s.trim()).filter(s=>s.startsWith(PIPELINE_COOKIE+'='));
 if(!cookies.length)return null;
 if(cookies.length!==1)pipelineFail('INVALID_INQUIRY_SESSION',401);
 let value;try{value=await unseal(cookies[0].slice(PIPELINE_COOKIE.length+1),env,'pipeline-session');}catch{pipelineFail('INVALID_INQUIRY_SESSION',401);}
 if(!pipelineId(value.id)||!Number.isFinite(value.expiresAt)||value.expiresAt<Date.now()||value.expiresAt>Date.now()+86400000)pipelineFail('INVALID_INQUIRY_SESSION',401);
 return value;
}
