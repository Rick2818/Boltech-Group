export function preparePipelineRecord(record){
 const rec=structuredClone(record),answers=rec.answers||{};
 rec.missing=pipelineQuestions.filter(([key])=>!answers[key]?.value).map(([key])=>key);
 const critical=pipelineQuestions.slice(0,5).map(([key])=>key);
 rec.qualification={status:critical.every(k=>answers[k]?.value)?'READY_FOR_REVIEW':'INCOMPLETE',
  confirmed:answers,inferences:[],missing:rec.missing};
 // A draft is never a price promise or a buyer commitment. Preserve owner edits.
 if(!rec.proposal||rec.proposal.autoGenerated){
  const fingerprint=JSON.stringify({need:rec.need,answers});
  if(rec.proposal?.basis!==fingerprint){
   rec.proposal={revision:(rec.proposal?.revision||0)+1,status:'DRAFT',autoGenerated:true,basis:fingerprint,
    scope:rec.need,deliverables:['Definición del flujo solicitado','Configuración de las integraciones confirmadas','Validación contra criterios acordados'],
    integrations:answers.tools?.value||null,acceptanceCriteria:answers.goal?.value||null,
    exclusions:answers.limits?.value||null,missing:rec.missing,
    amountCents:null,currency:'USD',priceStatus:'OWNER_QUOTE_REQUIRED',approvedAt:null,externalSent:false};
   rec.approval=null;
  }
 }
 rec.status=rec.closure?'CLOSED':rec.consent?.withdrawn?'CONSENT_WITHDRAWN':rec.proposal?.status==='OWNER_APPROVED'?'PROPOSAL_APPROVED':'REVIEW_REQUIRED';
 if(!rec.followups)rec.followups=[];
 return rec;
}
export function pipelineTransition(record,input,now=new Date().toISOString()){
 let rec=structuredClone(record);
 if(rec.closure||rec.consent?.withdrawn)pipelineFail('INQUIRY_STOPPED',409);
 const note=pipelineText(input.note,1200);
 if(input.action==='proposal'){
  const scope=pipelineText(input.scope,3000),exclusions=pipelineText(input.exclusions,1000);
  if(!scope||!exclusions)pipelineFail('PROPOSAL_INCOMPLETE',400);
  const amount=input.amountCents??null;
  if(amount!==null&&(!Number.isSafeInteger(amount)||amount<=0||amount>100000000))pipelineFail('INVALID_PRICE',400);
  rec.proposal={...rec.proposal,scope,exclusions,amountCents:amount,autoGenerated:false,revision:(rec.proposal?.revision||0)+1,
   status:'DRAFT',approvedAt:null,externalSent:false,priceStatus:amount===null?'OWNER_QUOTE_REQUIRED':'OWNER_ENTERED'};
  rec.approval=null;
  rec.followups=rec.followups.map(f=>({...f,status:'STOPPED',stopReason:'PROPOSAL_CHANGED'}));
 }else if(input.action==='approve'){
  if(input.confirmed!==true||input.proposalRevision!==rec.proposal?.revision||rec.proposal?.status!=='DRAFT'||
    rec.qualification.status!=='READY_FOR_REVIEW'||rec.proposal.amountCents===null)pipelineFail('REVIEW_AND_PRICE_REQUIRED',409);
  rec.proposal.status='OWNER_APPROVED';rec.proposal.approvedAt=now;
  rec.customerResponsePendingReview=false;
  rec.approval={id:crypto.randomUUID(),proposalRevision:rec.proposal.revision,action:'INTERNAL_PROPOSAL_APPROVAL',approvedAt:now,externalSendAuthorized:false};
  rec.followups.push({id:crypto.randomUUID(),note:'Borrador: confirmar requisitos pendientes de '+rec.need.slice(0,400)+'.',channel:'INTERNAL',
   scheduledAt:new Date(Date.parse(now)+86400000).toISOString(),proposalRevision:rec.proposal.revision,status:'PREPARED',externalSendAuthorized:false,providerReceipt:null});
 }else if(['reject','request_changes'].includes(input.action)){
  if(!note)pipelineFail('REVIEW_NOTE_REQUIRED',400);
  rec.proposal.status=input.action==='reject'?'REJECTED':'CHANGES_REQUESTED';rec.proposal.approvedAt=null;rec.approval=null;
  rec.reviewNote=note;
  rec.followups=rec.followups.map(f=>({...f,status:'STOPPED',stopReason:input.action.toUpperCase()}));
  if(input.action==='reject')rec.closure={outcome:'LOST',recordedAt:now,evidence:note};
 }else if(input.action==='followup'){
  if(rec.proposal?.status!=='OWNER_APPROVED'||!note||input.sent===true||!['INTERNAL',undefined].includes(input.channel))pipelineFail('INTERNAL_DRAFT_ONLY',409);
  const scheduled=new Date(input.scheduledAt||Date.parse(now)+86400000);
  if(!Number.isFinite(+scheduled)||+scheduled<Date.parse(now)||+scheduled>Date.parse(now)+90*86400000)pipelineFail('INVALID_SCHEDULE',400);
  if(rec.followups.length>=20)pipelineFail('FOLLOWUP_LIMIT',409);
  rec.followups.push({id:crypto.randomUUID(),note,channel:'INTERNAL',scheduledAt:scheduled.toISOString(),
   proposalRevision:rec.proposal.revision,status:'PREPARED',externalSendAuthorized:false,providerReceipt:null});
 }else if(input.action==='close'){
  if(!['WON','LOST'].includes(input.outcome)||!pipelineText(input.evidence,500)||input.confirmed!==true||
   (input.outcome==='WON'&&(input.customerAccepted!==true||rec.proposal?.status!=='OWNER_APPROVED')))pipelineFail('CLOSURE_EVIDENCE_REQUIRED',409);
  rec.closure={outcome:input.outcome,evidence:pipelineText(input.evidence,500),recordedAt:now,paymentVerified:false};
  rec.followups=rec.followups.map(f=>({...f,status:'STOPPED',stopReason:'CLOSED'}));
 }else pipelineFail('ACTION_NOT_ALLOWED',400);
 rec.version++;rec.updatedAt=now;
 rec.status=rec.closure?'CLOSED':rec.proposal.status==='OWNER_APPROVED'?'PROPOSAL_APPROVED':rec.proposal.status;
 return rec;
}
export function createPipelineStore(env,fetchFn=fetch){
 const ready=pipelineReadiness(env);
 if(!ready.ready)pipelineFail('PIPELINE_NOT_CONFIGURED');
 async function call(path,body){
  let response;
  try{response=await fetchFn(pipelineBase(env)+'/rest/v1/'+path,{method:body?'POST':'GET',redirect:'error',signal:AbortSignal.timeout(10000),
   headers:{apikey:pipelineServiceKey(env),Authorization:'Bearer '+pipelineServiceKey(env),'Content-Type':'application/json'},
   ...(body?{body:JSON.stringify(body)}:{})});}catch{pipelineFail('PIPELINE_DATABASE_UNAVAILABLE');}
  if(!response.ok){const data=await response.json().catch(()=>({}));if(data.message==='STALE_VERSION')pipelineFail('STALE_VERSION',409);if([401,403].includes(response.status))pipelineFail('PIPELINE_DATABASE_AUTH_REQUIRED');pipelineFail('PIPELINE_DATABASE_UNAVAILABLE');}
  try{return await response.json();}catch{pipelineFail('PIPELINE_DATABASE_UNAVAILABLE');}
 }
 return {
  async read(id){if(!pipelineId(id))pipelineFail('INVALID_ID',400);const rows=await call('crm_leads?select=leo_record&id=eq.'+id+'&source=eq.LEO_INBOUND_V1');return rows[0]?.leo_record||null;},
  async list(){return (await call('crm_leads?select=leo_record&source=eq.LEO_INBOUND_V1&order=updated_at.desc&limit=50')).map(r=>r.leo_record);},
  save(record,expectedVersion,eventKey){return call('rpc/save_leo_inquiry',{p_record:record,p_expected_version:expectedVersion,p_event_key:eventKey});},
  tick(){return call('rpc/tick_leo_followups',{});},
  async probe(){await call('crm_leads?select=id&source=eq.LEO_INBOUND_V1&limit=0');return true;}
 };
}
